import Areas

print("The area of a triangle with base 9 and height 4 is: " + str(Areas.triangle(9, 4)))
print("The area of a rectangle with base 3 and height 4 is: " + str(Areas.rectangle(8, 5))) 
print("The area of a circle with radius 7 is: " + str(Areas.circle(7))) 
print("The area of a square with side 5 is: " + str(Areas.square(5)))
print("The area of a trapezoid with base1 3, base2 4, and height 5 is: " + str(Areas.trapezoid(3, 4, 5)))
print("The area of a donut with outer radius 5 and inner radius 3 is: " + str(Areas.donut(5, 3)))